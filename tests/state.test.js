import test from "node:test";
import assert from "node:assert/strict";
import { newGame, act, persist, loadGame, sanitize, itemCount, nextMission, missionStep, timeLabel } from "../src/state.js";
const go = (g, place) => act(g, "travel", { place }).game;
test("new game has place, starter money, mission, and correct clock", () => {
  const g = newGame();
  assert.equal(g.location, "town");
  assert.equal(g.coins, 64);
  assert.equal(nextMission(g).id, "book");
  assert.equal(missionStep(g), 0);
  assert.equal(timeLabel(g), "8:30 AM");
});
test("save/reload preserves character and location", () => {
  const cache = new Map();
  const store = { getItem: k => cache.get(k) || null, setItem: (k,v) => cache.set(k,v) };
  let g = act(newGame(), "customize", { avatar: { name: "Mimi", hair: "pigtails", outfitColor: "#739be1" } }).game;
  g = go(g, "home");
  assert.equal(persist(g, store), true);
  const saved = loadGame(store);
  assert.equal(saved.avatar.name, "Mimi");
  assert.equal(saved.avatar.hair, "pigtails");
  assert.equal(saved.avatar.outfitColor, "#739be1");
  assert.equal(saved.location, "home");
});
test("school book can be collected once, kept and studied at home", () => {
  let g = newGame();
  assert.equal(act(g, "book").ok, false);
  g = go(g, "school");
  const r = act(g, "book");
  assert.equal(r.ok, true);
  g = r.game;
  assert.equal(itemCount(g, "book"), 1);
  assert.equal(act(g, "book").ok, false);
  assert.equal(nextMission(g).id, "study");
  g = go(g, "home");
  g = act(g, "study").game;
  assert.equal(g.stats.knowledge, 18);
  assert.equal(nextMission(g).id, "outfit");
});
test("boutique unlocks and equips outfits, wardrobe persists", () => {
  let g = go(newGame(), "boutique");
  assert.equal(act(g, "buy-outfit", { id: "potato" }).ok, false);
  const coins = g.coins;
  g = act(g, "buy-outfit", { id: "dress" }).game;
  assert.equal(g.coins, coins - 18);
  assert.equal(g.avatar.outfit, "dress");
  assert.equal(g.wardrobe.includes("dress"), true);
  assert.equal(act(g, "buy-outfit", { id: "dress" }).ok, false);
  g = go(g, "home");
  assert.equal(act(g, "equip", { id: "hoodie" }).ok, false);
  assert.equal(act(g, "equip", { id: "shirt" }).game.avatar.outfit, "shirt");
});
test("shop food and eat from inventory, no duplicate consumption", () => {
  let g = go(newGame(), "market");
  assert.equal(act(g, "buy", { id: "book" }).ok, false);
  const beforeMoney = g.coins;
  g = act(g, "buy", { id: "apple" }).game;
  assert.equal(g.coins, beforeMoney - 6);
  assert.equal(itemCount(g, "apple"), 1);
  g = go(g, "home");
  const before = g.stats.hunger;
  g = act(g, "eat", { id: "apple" }).game;
  assert.equal(itemCount(g, "apple"), 0);
  assert.ok(g.stats.hunger > before);
  assert.equal(act(g, "eat", { id: "apple" }).ok, false);
});
test("home bed restores energy and mission progress", () => {
  const atTown = newGame();
  assert.equal(act(atTown, "rest").ok, false);
  let g = go(atTown, "home");
  g.stats.energy = 22;
  const r = act(g, "rest");
  assert.equal(r.game.stats.energy, 68);
  assert.equal(r.game.progress.rest, true);
});
test("corrupt saves and fake inventory cannot inject state", () => {
  assert.equal(loadGame({ getItem: () => "{" }).location, "town");
  const raw = newGame();
  raw.location = "fake";
  raw.inventory = { banana: 2, apple: 400 };
  raw.avatar.name = "<script>hello</script>";
  const safe = sanitize(raw);
  assert.equal(safe.location, "town");
  assert.equal(safe.inventory.banana, undefined);
  assert.equal(safe.inventory.apple, 99);
  assert.ok(!safe.avatar.name.includes("<"));
});
test("failed actions do not mutate original and time advances across midnight", () => {
  let g = go(newGame(), "market");
  g.coins = 0;
  const snapshot = JSON.stringify(g);
  assert.equal(act(g, "buy", { id: "bun" }).ok, false);
  assert.equal(JSON.stringify(g), snapshot);
  g = go(newGame(), "park");
  g.minute = 1436;
  g = act(g, "play").game;
  assert.equal(g.day, 2);
  assert.ok(g.minute < 1440);
});
test("full mission walkthrough: school, study, boutique, market, food, bed", () => {
  let g = go(newGame(), "school");
  g = act(g, "book").game;
  g = act(g, "study").game;
  g = go(g, "boutique");
  g = act(g, "buy-outfit", { id: "dress" }).game;
  g = go(g, "market");
  g = act(g, "buy", { id: "milk" }).game;
  g = go(g, "home");
  g = act(g, "eat", { id: "milk" }).game;
  g = act(g, "rest").game;
  assert.equal(missionStep(g), 6);
  assert.equal(nextMission(g), null);
});
